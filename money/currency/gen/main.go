// Command gen writes list.go, the currency table, from currencies.csv. Run
// it with go generate ./money/currency after changing the CSV.
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

var codePattern = regexp.MustCompile(`^[A-Z][A-Z0-9]{1,9}$`)

// header is currencies.csv's first row, which must be exactly this: a CSV
// without it would otherwise lose its first currency as the header.
var header = []string{"code", "name", "kind", "decimals"}

func main() {
	file, err := os.Open("currencies.csv")
	if err != nil {
		log.Fatal(err)
	}
	defer file.Close()
	reader := csv.NewReader(file)
	reader.FieldsPerRecord = len(header)
	rows, err := reader.ReadAll()
	if err != nil {
		log.Fatal(err)
	}
	if len(rows) < 2 || !slices.Equal(rows[0], header) {
		log.Fatalf("currencies.csv must start with the row %s and list at least one currency", strings.Join(header, ","))
	}

	var constants, entries bytes.Buffer
	seen := map[string]bool{}
	for i, row := range rows[1:] {
		code, name, kind, decimals := row[0], row[1], row[2], row[3]
		places, err := strconv.Atoi(decimals)
		switch {
		case !codePattern.MatchString(code):
			log.Fatalf("row %d: bad code %q", i+2, code)
		case seen[code]:
			log.Fatalf("row %d: %s listed twice", i+2, code)
		case kind != "fiat" && kind != "crypto":
			log.Fatalf("row %d: bad kind %q", i+2, kind)
		case err != nil || places < 0 || places > 18:
			log.Fatalf("row %d: bad decimals %q", i+2, decimals)
		}
		seen[code] = true
		kindName := map[string]string{"fiat": "Fiat", "crypto": "Crypto"}[kind]
		fmt.Fprintf(&constants, "\t%s = %q\n", code, code)
		fmt.Fprintf(&entries, "\t{code: %s, name: %q, kind: %s, decimals: %d},\n", code, name, kindName, places)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./gen from currencies.csv; DO NOT EDIT.\n\npackage currency\n\n")
	out.WriteString("// The currency codes.\nconst (\n")
	out.Write(constants.Bytes())
	out.WriteString(")\n\n// list is every currency, in currencies.csv's order.\nvar list = []Currency{\n")
	out.Write(entries.Bytes())
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("list.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
