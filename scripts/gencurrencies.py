#!/usr/bin/env python3
"""Writes ledger/core_currency_data.go from scripts/currencies.csv.

Usage: python3 scripts/gencurrencies.py [repo root]
"""
import csv
import os
import sys

KINDS = {"fiat": "Fiat", "crypto": "Crypto", "stablecoin": "Stablecoin"}


def go_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..")
    src = os.path.join(root, "scripts", "currencies.csv")
    rows = []
    with open(src, encoding="utf-8") as f:
        lines = [ln for ln in f if ln.strip() and not ln.startswith("#")]
    for n, rec in enumerate(csv.reader(lines), 1):
        if len(rec) != 7:
            sys.exit(f"currencies.csv: row {n} has {len(rec)} fields, want 7: {rec}")
        code, kind, decimals, display, trim, symbol, name = rec
        if kind not in KINDS:
            sys.exit(f"currencies.csv: {code}: unknown kind {kind!r}")
        decimals, display = int(decimals), int(display)
        if decimals > 18 or display > decimals:
            sys.exit(f"currencies.csv: {code}: decimals {decimals}, display {display}")
        rows.append((code, KINDS[kind], decimals, display, trim == "1", symbol, name))

    codes = [r[0] for r in rows]
    if len(set(codes)) != len(codes):
        sys.exit("currencies.csv: duplicate codes")

    w = max(len(go_str(r[0])) for r in rows) + 1
    out = [
        "// Code generated by scripts/gencurrencies.py from scripts/currencies.csv. DO NOT EDIT.",
        "",
        "package ledger",
        "",
        "// Currencies lists every currency humanblnk knows without configuration:",
        "// every current ISO 4217 code, plus major crypto currencies and stablecoins.",
        "// Treat it as read-only; change or add currencies with Config.Currencies.",
        "var Currencies = map[string]Currency{",
    ]
    for code, kind, dec, disp, trim, symbol, name in sorted(rows, key=lambda r: r[0]):
        rule = f"DisplayRule{{Decimals: {disp}" + (", TrimZeros: true}" if trim else "}")
        out.append(
            f"\t{(go_str(code) + ':').ljust(w)} {{Code: {go_str(code)}, Name: {go_str(name)}, Kind: {kind}, "
            f"Symbol: {go_str(symbol)}, Precision: 1e{dec}, Display: {rule}}},"
        )
    out.append("}")
    dst = os.path.join(root, "ledger", "core_currency_data.go")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
